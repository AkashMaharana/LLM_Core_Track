from sklearn.linear_model import LinearRegression


def main():

    # ---------------------------------------------------------
    # Training data
    #
    # X = input/features
    # y = target/output
    # ---------------------------------------------------------

    X = [
        [1000],
        [1500],
        [2000],
        [2500],
        [3000],
    ]

    y = [
        100000,
        150000,
        200000,
        250000,
        300000,
    ]

    # ---------------------------------------------------------
    # 1. Create model
    # ---------------------------------------------------------

    model = LinearRegression()

    # ---------------------------------------------------------
    # 2. Train model
    # ---------------------------------------------------------

    model.fit(
        X,
        y,
    )

    # ---------------------------------------------------------
    # 3. Predict new house price
    # ---------------------------------------------------------

    prediction = model.predict(
        [[1800]]
    )

    print(
        "Predicted price:",
        round(prediction[0], 2)
    )

    # ---------------------------------------------------------
    # 4. Inspect learned parameters
    # ---------------------------------------------------------

    print(
        "Weight:",
        model.coef_[0]
    )

    print(
        "Intercept:",
        model.intercept_
    )


if __name__ == "__main__":
    main()